-- CoolERP — durable process engine tables.
-- Tracks multi-step business-process instances and their GL postings.

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
CREATE TYPE instance_status AS ENUM ('active', 'completed', 'cancelled');

-- ---------------------------------------------------------------------------
-- Role → account mapping
-- Human-readable role names (matching posting_rule.debit / .credit in YAML)
-- mapped to account codes in the chart of accounts.
-- ---------------------------------------------------------------------------
CREATE TABLE account_roles (
    role         TEXT NOT NULL PRIMARY KEY,
    account_code TEXT NOT NULL REFERENCES accounts (code)
);

