"""Reproducible CoolERP money overlay; never edits Tungsten-owned output.

Builds a disposable package tree from generated/. The wheel build hook invokes
this file. Fail closed if the reviewed OpenAPI integer inventory or emitted
annotation shapes change. See MONEY_OVERLAY.md for scope and provenance.
"""
import ast
import hashlib
import json
from pathlib import Path

MONEY = {
    "AdvanceInstanceRequest": ["amounts"],
    "AgingBucket": ["total_cents"],
    "BalanceResponse": ["balance", "credits", "debits"],
    "LineRequest": ["credit", "debit"],
    "OverviewResponse": ["ap_cents", "ar_cents", "cash_cents", "expenses_cents", "revenue_cents"],
    "SubledgerSection": ["control_balance_cents", "difference_cents", "subledger_total_cents"],
    "TrialBalanceLine": ["balance_cents", "credits_cents", "debits_cents"],
    "TrialBalanceResponse": ["total_credits_cents", "total_debits_cents"],
}
NON_MONEY = {
    "InstanceResponse.id", "OverviewResponse.account_count", "PostResultResponse.entry_id",
    "ReceiveStockResponse.move_id", "StepLogResponse.entry_id", "StepLogResponse.id",
    "StepLogResponse.instance_id",
}
ROOT = Path(__file__).resolve().parent


def once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"expected exactly one reviewed generation pattern: {old!r}")
    return text.replace(old, new, 1)


def prepare(root=ROOT):
    spec_bytes = (root / "openapi.json").read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(spec_bytes).hexdigest() != "56fb5cb55d542b6cdfaad6cba6b04ba8e42a61b5d98850e0ef0466b2805d5bb5":
        raise ValueError("OpenAPI changed: review monetary fields before updating the overlay pin")
    schema = json.loads(spec_bytes)
    inventory = set()
    for name, model in schema["components"]["schemas"].items():
        for field, value in model.get("properties", {}).items():
            if value.get("format") == "int64" or value.get("additionalProperties", {}).get("format") == "int64":
                inventory.add(f"{name}.{field}")
    monetary = {f"{model}.{field}" for model, fields in MONEY.items() for field in fields}
    if inventory != monetary | NON_MONEY:
        raise ValueError(f"OpenAPI integer inventory changed: {inventory ^ (monetary | NON_MONEY)}")

    source = root / "generated" / "coolerp_sdk"
    texts = {p.relative_to(source): p.read_text(encoding="utf-8")
             for p in source.rglob("*") if p.is_file() and (p.suffix == ".py" or p.name == "py.typed")}
    for path in [Path("models/coolerp.py"), Path("_descriptors.py"), Path("_internal.py"), Path("client.py")]:
        if not texts[path].startswith("# Generated by tungsten 0.1.6. Do not edit.\n"):
            raise ValueError(f"unreviewed generator output: {path}")
    model_path = Path("models/coolerp.py")
    models = texts[model_path]
    lines = models.splitlines(keepends=True)
    covered = set()
    for cls in ast.parse(models).body:
        if not isinstance(cls, ast.ClassDef) or cls.name not in MONEY:
            continue
        for field in cls.body:
            if not isinstance(field, ast.AnnAssign) or not isinstance(field.target, ast.Name):
                continue
            if field.target.id not in MONEY[cls.name]:
                continue
            if field.lineno != field.end_lineno:
                raise ValueError("review new multiline model annotation")
            lines[field.lineno - 1] = once(lines[field.lineno - 1], "_internal.Int", "Cents")
            covered.add(f"{cls.name}.{field.target.id}")
    if covered != monetary:
        raise ValueError(f"missing monetary fields in generated models: {monetary - covered}")
    texts[model_path] = once("".join(lines), "from .. import _internal",
                            "from .. import _internal\nfrom ..custom.cents import Cents")

    # Flattened request arguments bypass AdvanceInstanceRequest, so patch the
    # descriptor as well. Journal lines already pass through LineRequest.
    desc = texts[Path("_descriptors.py")]
    desc = once(desc, '"amounts": _internal.Arg(dict[str, _internal.Int], required=False)',
                '"amounts": _internal.Arg(dict[str, Cents], required=False)')
    texts[Path("_descriptors.py")] = once(desc, "from . import _internal",
                                          "from . import _internal\nfrom .custom.cents import Cents")
    internal = texts[Path("_internal.py")]
    # Revalidate model instances, including mutated/model_construct instances,
    # rather than trusting that their initial constructor already checked them.
    internal = once(internal, 'ConfigDict(populate_by_name=True, protected_namespaces=(), strict=True)',
                    'ConfigDict(populate_by_name=True, protected_namespaces=(), strict=True, revalidate_instances="always")')
    # Invalid server money must not silently become a successful raw response.
    # Explicit caller options can still select warn/off, as documented.
    internal = once(internal, "base = options if options is not None else ClientOptions()",
                    'base = options if options is not None else ClientOptions(validate_responses="strict")')
    texts[Path("_internal.py")] = internal
    client = texts[Path("client.py")]
    default = 'validate_responses: Literal["off", "warn", "strict"] | None = None'
    if client.count(default) != 2:
        raise ValueError("review changed sync/async response validation defaults")
    texts[Path("client.py")] = client.replace(default, default.replace("= None", '= "strict"'))

    destination = (root / "build" / "validated" / "coolerp_sdk").resolve()
    destination.relative_to(root.resolve())
    # Remove stale files only inside this exact disposable build subtree.
    # No recursive deletion and no modification of the raw generated package.
    expected = set(texts) | {Path("_money_overlay.json")}
    for stale in destination.rglob("*"):
        if stale.is_file() and stale.relative_to(destination) not in expected:
            stale.resolve().relative_to(destination)
            stale.unlink()
    banner = "# Applied by sdk/python/prepare_sdk.py: reviewed CoolERP cents overlay.\n"
    for relative, content in texts.items():
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        if relative in {model_path, Path("_descriptors.py"), Path("_internal.py"), Path("client.py")}:
            content = banner + content
        target.write_text(content, encoding="utf-8", newline="\n")
    receipt = {
        "overlay": 1, "generator": "tungsten 0.1.6",
        "hash_normalization": "CRLF to LF",
        "openapi_sha256": hashlib.sha256(spec_bytes).hexdigest(),
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes().replace(b"\r\n", b"\n")).hexdigest(),
        "monetary_fields": sorted(monetary), "unchanged_int64_fields": sorted(NON_MONEY),
        "output_sha256": {str(p).replace("\\", "/"): hashlib.sha256((destination / p).read_bytes()).hexdigest()
                          for p in sorted(texts)},
    }
    (destination / "_money_overlay.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")
    return destination


if __name__ == "__main__":
    print(prepare())
